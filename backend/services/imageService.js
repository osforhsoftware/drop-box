const fs = require("fs");
const path = require("path");
const sharp = require("sharp");
const { MIN_QUALITY, resolveImageSettings } = require("../lib/imageSettings");

const QUALITY_STEP = 10;

const ALLOWED_FORMATS = new Set(["jpeg", "png", "webp"]);

const VARIANTS = [
  { key: "thumb", width: 300 },
  { key: "medium", width: 800 },
  { key: "large", width: 1600 },
];

class ImageInputError extends Error {
  constructor(message) {
    super(message);
    this.name = "ImageInputError";
    this.statusCode = 400;
  }
}

function imageSettings(options = {}) {
  const resolved = resolveImageSettings({
    image_compress_enabled: options.enabled ?? options.image_compress_enabled,
    image_max_width: options.image_max_width,
    image_target_kb: options.targetKb ?? options.image_target_kb,
    image_webp_quality: options.quality ?? options.image_webp_quality,
  });
  const explicitWidth = Number(options.maxWidth);
  const maxWidth = Number.isFinite(explicitWidth) && explicitWidth >= 16
    ? Math.min(4096, Math.round(explicitWidth))
    : resolved.image_max_width;
  return {
    ...resolved,
    enabled: resolved.image_compress_enabled,
    maxWidth,
    targetKb: resolved.image_target_kb,
    quality: resolved.image_webp_quality,
  };
}

/** Reject anything sharp cannot decode as JPG, PNG, or WebP. MIME headers are not trusted. */
async function assertSupportedImage(buffer) {
  if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
    throw new ImageInputError("Invalid image file. Use JPG, PNG, or WebP.");
  }

  let meta;
  try {
    meta = await sharp(buffer, { failOn: "error" }).metadata();
  } catch {
    throw new ImageInputError("Invalid image file. Use JPG, PNG, or WebP.");
  }

  const format = String(meta.format || "").toLowerCase();
  if (!ALLOWED_FORMATS.has(format) || !meta.width || !meta.height) {
    throw new ImageInputError("Only JPG, PNG, and WebP images are allowed.");
  }
  return meta;
}

/**
 * Encode one WebP. EXIF orientation is applied, then metadata is dropped
 * (sharp omits metadata unless withMetadata() is called). Alpha is kept
 * so PNG transparency survives the conversion.
 */
async function encodeWebp(buffer, { maxWidth, quality }) {
  return sharp(buffer, { failOn: "error" })
    .rotate()
    .resize({
      width: maxWidth,
      height: maxWidth,
      withoutEnlargement: true,
      fit: "inside",
    })
    .webp({
      quality,
      alphaQuality: 100,
    })
    .toBuffer();
}

/**
 * Convert an image buffer to a compressed WebP.
 * Quality starts at IMAGE_WEBP_QUALITY (default 85) and drops by 10 until
 * the file is under IMAGE_TARGET_KB (default 150) or quality reaches 40.
 * @returns {Promise<{ buffer: Buffer, quality: number }>}
 */
async function convertToWebp(buffer, options = {}) {
  await assertSupportedImage(buffer);
  const settings = imageSettings(options);
  const targetBytes = settings.targetKb * 1024;

  let quality = settings.quality;
  let output;
  try {
    output = await encodeWebp(buffer, { maxWidth: settings.maxWidth, quality });
    while (output.length > targetBytes && quality > MIN_QUALITY) {
      quality = Math.max(MIN_QUALITY, quality - QUALITY_STEP);
      output = await encodeWebp(buffer, { maxWidth: settings.maxWidth, quality });
    }
  } catch (err) {
    if (err instanceof ImageInputError) throw err;
    throw err;
  }

  return { buffer: output, quality };
}

/** Storage names are generated by the server. Reject client paths and unexpected characters. */
function sanitizeBaseName(baseName) {
  const raw = String(baseName || "");
  if (!/^[a-zA-Z0-9_-]+$/.test(raw)) {
    throw new ImageInputError("Invalid image name.");
  }
  return raw;
}

/**
 * Write thumb (300), medium (800), and large (1600) WebP variants.
 * @returns {Promise<{ thumb: string, medium: string, large: string }>} file names only
 */
function extensionForFormat(format) {
  if (format === "jpeg") return "jpg";
  if (format === "png" || format === "webp") return format;
  throw new ImageInputError("Only JPG, PNG, and WebP images are allowed.");
}

/**
 * Compress to WebP when enabled. When disabled, keep the original bytes
 * after the format check so transparency and pixel size stay intact.
 */
async function prepareUpload(buffer, options = {}) {
  const settings = imageSettings(options);
  const meta = await assertSupportedImage(buffer);
  if (!settings.enabled) {
    return {
      buffer,
      ext: extensionForFormat(meta.format),
      compressed: false,
      quality: null,
      width: meta.width,
      height: meta.height,
    };
  }
  const converted = await convertToWebp(buffer, settings);
  const outMeta = await sharp(converted.buffer).metadata();
  return {
    buffer: converted.buffer,
    ext: "webp",
    compressed: true,
    quality: converted.quality,
    width: outMeta.width,
    height: outMeta.height,
  };
}

/**
 * Replace a saved customer/product image with WebP when compression is on.
 * GIF files are left as-is. Overlay template PNGs must not be passed here.
 */
async function compressDiskImage(filePath, options = {}) {
  const settings = imageSettings(options);
  const ext = path.extname(filePath).toLowerCase();
  if (!settings.enabled || ext === ".gif") {
    return { filePath, compressed: false };
  }
  const buffer = await fs.promises.readFile(filePath);
  if (ext === ".webp") {
    try {
      const meta = await sharp(buffer).metadata();
      const longest = Math.max(meta.width || 0, meta.height || 0);
      if (buffer.length <= settings.targetKb * 1024 && longest > 0 && longest <= settings.maxWidth) {
        return { filePath, compressed: true, width: meta.width, height: meta.height };
      }
    } catch {
      /* fall through and re-encode */
    }
  }
  const prepared = await prepareUpload(buffer, settings);
  if (!prepared.compressed) return { filePath, compressed: false };
  const dest = filePath.replace(/\.[^.]+$/, ".webp");
  await fs.promises.writeFile(dest, prepared.buffer);
  if (dest !== filePath) await fs.promises.unlink(filePath).catch(() => {});
  return {
    filePath: dest,
    compressed: true,
    quality: prepared.quality,
    width: prepared.width,
    height: prepared.height,
  };
}

/**
 * Case overlay PNGs are print masks. Never resize or convert them —
 * camera cutouts are stored in these exact pixels.
 */
async function assertOverlayPng(filePath, { width, height } = {}) {
  let meta;
  try {
    meta = await sharp(filePath, { failOn: "error" }).metadata();
  } catch {
    return { error: "Could not read overlay PNG. Export it again as a transparent PNG." };
  }
  if (String(meta.format || "").toLowerCase() !== "png") {
    return { error: "Phone case overlays must stay PNG. Image compression is not applied to templates." };
  }
  if (!meta.hasAlpha) {
    return { error: "Overlay PNG needs a transparent background." };
  }
  if (!meta.width || !meta.height || meta.width < 360 || meta.height < 720) {
    return { error: "Overlay PNG is too small. Use at least 360×720 px." };
  }
  const expectedW = Number(width);
  const expectedH = Number(height);
  if (expectedW > 0 && expectedH > 0 && (meta.width !== expectedW || meta.height !== expectedH)) {
    return {
      error: `PNG is ${meta.width}×${meta.height} px, but the editor reported ${expectedW}×${expectedH}. Upload the original PNG without resizing.`,
    };
  }
  return { ok: true, width: meta.width, height: meta.height };
}

async function createVariants(buffer, baseName, outDir, options = {}) {
  const safeBase = sanitizeBaseName(baseName);
  const settings = imageSettings(options);
  await fs.promises.mkdir(outDir, { recursive: true });

  const names = {};
  const written = [];
  try {
    for (const variant of VARIANTS) {
      const filename = `${safeBase}-${variant.key}.webp`;
      const encoded = await convertToWebp(buffer, {
        ...settings,
        maxWidth: Math.min(variant.width, settings.maxWidth),
      });
      const dest = path.join(outDir, filename);
      await fs.promises.writeFile(dest, encoded.buffer);
      written.push(dest);
      names[variant.key] = filename;
    }
    return names;
  } catch (err) {
    await Promise.all(written.map((filePath) => fs.promises.unlink(filePath).catch(() => {})));
    throw err;
  }
}

module.exports = {
  ImageInputError,
  convertToWebp,
  createVariants,
  prepareUpload,
  compressDiskImage,
  assertOverlayPng,
};
